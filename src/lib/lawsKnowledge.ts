export function findMatchingLaw(question: string, server: string): string | null {
  const q = question.toLowerCase();
  
  for (const topic of LAW_TOPICS) {
    let matchCount = 0;
    for (const kw of topic.keywords) {
      if (q.includes(kw)) {
        matchCount++;
      }
    }
    // High confidence match
    if (matchCount >= 1) {
      return topic.response(server, question);
    }
  }

  return null;
}
