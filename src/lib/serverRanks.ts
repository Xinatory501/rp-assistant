export function getServerDepartments(org: string, serverName = "Red"): string[] {
  const shortOrg = org.startsWith("ПР") ? "ПР" :
    org.startsWith("ВЧ") ? "ВЧ" :
    org.startsWith("ЕСС") ? "ЕСС" :
    org.startsWith("ТРК") ? "ТРК" :
    org.startsWith("Суд") ? "Суд" : org;

  const sUpper = (serverName || "RED").toUpperCase();
  const serverOverrides = SERVER_SPECIAL_DEPTS[sUpper]?.[shortOrg];
  if (serverOverrides && serverOverrides.length > 0) {
    return serverOverrides;
  }

  return COMMON_DEPTS[shortOrg] || COMMON_DEPTS[org] || ["Основной состав"];
}

export function getServerRanks(org: string, _serverName = "Red"): string[] {
  const shortOrg = org.startsWith("ПР") ? "ПР" :
    org.startsWith("ВЧ") ? "ВЧ" :
    org.startsWith("ЕСС") ? "ЕСС" :
    org.startsWith("ТРК") ? "ТРК" :
    org.startsWith("Суд") ? "Суд" : org;

  return COMMON_RANKS[shortOrg] || COMMON_RANKS[org] || ["Сотрудник [1]"];
}
