import { getRadioRussianSurname, transliterateNickToRussian } from './lib/nameTranslit';

export function getCleanRank(rank?: string): string {
  if (!rank) return 'Лейтенант';
  return rank.replace(/\s*\[\d+\]\s*/g, '').trim();
}

export function renderTemplate(template: string, profile: {
  rank: string; name: string; org: string; dept: string;
  post: string; callsign: string; nameRu?: string;
}, extras: ReportVars = {}): string {
  const count = extras.count || '2';
  const status = extras.status || 'стабильное';
  const partner = extras.partner || 'Иванов';
  
  const orgTag = getShortOrgTag(extras.org || profile.org);
  const deptTag = getShortDeptTag(extras.dept || profile.dept) || orgTag;
  
  let post = extras.post || profile.post || 'Мост г. Южный';
  if (post === 'Ю-2' || post === 'К-1' || post === 'Ю-1') {
    post = 'Мост г. Южный';
  }
  const rank = getCleanRank(extras.rank || profile.rank || 'Лейтенант');
  const rawName = extras.name || profile.name || 'Ivan_Ivanov';
  const customRu = profile.nameRu;
  const russianSurname = getRadioRussianSurname(rawName, customRu);
  const russianFullName = transliterateNickToRussian(rawName);

  const car = extras.car || 'BMW M5 F90';
  const number = extras.number || 'А777АА | 152';
  const article = extras.article || '39 УК';
  const targetOrg = getShortOrgTag(extras.targetOrg || 'УМВД');
  const reason = extras.reason || 'окончание дежурства';

  return template
    .replace(/\{dept\}/g, deptTag)
    .replace(/\{org\}/g, orgTag)
    .replace(/\{rank\}/g, rank)
    .replace(/\{name\}/g, russianSurname)
    .replace(/\{surname\}/g, russianSurname)
    .replace(/\{fullname\}/g, russianFullName)
    .replace(/\{nick\}/g, rawName)
    .replace(/\{post\}/g, post)
    .replace(/\{callsign\}/g, profile.callsign || 'Сокол-1')
    .replace(/\{count\}/g, count)
    .replace(/\{status\}/g, status)
    .replace(/\{partner\}/g, partner)
    .replace(/\{car\}/g, car)
    .replace(/\{number\}/g, number)
    .replace(/\{article\}/g, article)
    .replace(/\{targetOrg\}/g, targetOrg)
    .replace(/\{reason\}/g, reason);
}
