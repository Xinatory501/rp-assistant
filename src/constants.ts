export function getShortOrgTag(org?: string): string {
  if (!org) return 'УГИБДД';
  const o = org.trim();
  if (o.startsWith('ПР') || o.includes('Правительств')) return 'ПР';
  if (o.startsWith('ВЧ') || o.includes('Воинская часть')) return 'ВЧ';
  if (o.startsWith('ЕСС') || o.includes('Единая служба')) return 'ЕСС';
  if (o.startsWith('ТРК') || o.includes('Амазинг') || o.includes('СМИ')) return 'ТРК';
  if (o.startsWith('Суд') || o.includes('областной суд')) return 'Суд';
  if (o.includes('УГИБДД') || o.includes('ГИБДД')) return 'УГИБДД';
  if (o.includes('УМВД') || o.includes('МВД') || o.includes('Полиция')) return 'УМВД';
  if (o.includes('УФСБ') || o.includes('ФСБ')) return 'УФСБ';
  if (o.includes('УФСИН') || o.includes('ФСИН')) return 'УФСИН';
  return o.replace(/\s*\(.*?\)/g, '').trim();
}

export function getShortDeptTag(dept?: string): string {
  if (!dept) return '';
  const match = dept.match(/^([^(]+)/);
  return match ? match[1].trim() : dept.trim();
}

